#include "hw_dsp.h"
#include "hw_cordic.h"

/* ============================================================
 * 初始化 CORDIC 硬件协处理器 (仅初始化一次)
 * ============================================================ */
void HW_DSP_Init(void) {
    HW_CORDIC_Init();
}

/* ============================================================
 * 硬件加速：单周期三角函数 (直接读取寄存器)
 * 性能：耗时 < 50ns
 * ============================================================ */
void cordic_sincos(float angle, float *p_sin, float *p_cos) {
    HW_CORDIC_SinCos(angle, p_sin, p_cos);
}
